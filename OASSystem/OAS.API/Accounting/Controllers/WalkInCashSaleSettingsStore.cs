using Microsoft.EntityFrameworkCore;
using OAS.Contracts.Accounting.Settings;
using OAS.Domain.Accounting.Entities;
using OAS.Infrastructure.Persistence;

namespace OAS.API.Accounting.Controllers;

/// <summary>
/// Isolated storage for the cash customer used by anonymous walk-in invoices.
/// The setting is kept outside the accounting EF model to avoid changing
/// existing journal and customer relations or the accounting model snapshot.
/// </summary>
public static class WalkInCashSaleSettingsStore
{
    public static async Task<Guid?> GetCustomerIdAsync(OasDbContext db, CancellationToken ct)
    {
        var ids = await db.Database.SqlQueryRaw<Guid>(
            "SELECT [CustomerId] AS [Value] FROM [dbo].[tbl_WalkInCashSaleSettings] WHERE [Id] = 1")
            .ToListAsync(ct);
        return ids.Count == 0 ? null : ids[0];
    }

    public static async Task<WalkInCashCustomerSettingsDto> ReadAsync(OasDbContext db, CancellationToken ct)
    {
        var id = await GetCustomerIdAsync(db, ct);
        if (!id.HasValue)
            return new WalkInCashCustomerSettingsDto(null, null, null, null);

        var customer = await db.Customers.AsNoTracking().FirstOrDefaultAsync(x => x.Id == id.Value, ct);
        if (customer is null || !customer.IsActive || customer.IsCreditAllowed)
            return new WalkInCashCustomerSettingsDto(null, null, null, null);

        var account = await db.Set<Account>().AsNoTracking()
            .FirstOrDefaultAsync(x => x.Id == customer.AccountId, ct);
        if (account is null || !account.CanReceivePosting() ||
            account.AccountClass != OAS.Domain.Accounting.Enums.AccountClass.Asset ||
            account.NormalBalance != OAS.Domain.Accounting.Enums.NormalBalance.Debit)
            return new WalkInCashCustomerSettingsDto(null, null, null, null);

        return new WalkInCashCustomerSettingsDto(
            customer.Id, customer.CustomerCode, customer.NameAr, account.Code);
    }

    public static async Task SaveAsync(OasDbContext db, Guid? customerId, CancellationToken ct)
    {
        if (!customerId.HasValue)
        {
            await db.Database.ExecuteSqlRawAsync(
                "DELETE FROM [dbo].[tbl_WalkInCashSaleSettings] WHERE [Id] = 1", ct);
            return;
        }
        var id = customerId.Value;
        // SQL parameters are generated by EF; user-supplied values are not concatenated.
        await db.Database.ExecuteSqlInterpolatedAsync($@"
            UPDATE [dbo].[tbl_WalkInCashSaleSettings]
            SET [CustomerId] = {id}
            WHERE [Id] = 1;
            IF @@ROWCOUNT = 0
                INSERT INTO [dbo].[tbl_WalkInCashSaleSettings] ([Id], [CustomerId])
                VALUES (1, {id});", ct);
    }
}
